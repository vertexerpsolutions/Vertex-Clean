import React, { useState, useRef, useEffect } from 'react';
import { 
  Package, 
  FolderTree, 
  Store, 
  Vault, 
  Users, 
  MapPin, 
  Building2, 
  UserCheck, 
  Plus, 
  Trash2, 
  Edit3, 
  Save, 
  Search, 
  CheckCircle2, 
  AlertCircle, 
  AlertTriangle, 
  ArrowRight, 
  Layers, 
  Barcode, 
  Info, 
  X, 
  Lock, 
  ChevronDown, 
  ChevronLeft,
  ChevronRight,
  Folder,
  FolderOpen,
  Tag,
  Filter
} from 'lucide-react';
import { MasterDataSubTab } from '../../../types';
import { CustomerMasterView } from '../../customers/CustomerMasterView';
import { customerService } from '../../../services/customerService';
import { VendorMasterView } from '../../vendors/VendorMasterView';
import { vendorService } from '../../../services/vendorService';
import { TreasuryMasterView } from '../../treasuries/TreasuryMasterView';
import { treasuryService } from '../../../services/treasuryService';
import { WarehouseMasterView } from '../../warehouses/WarehouseMasterView';
import { warehouseService } from '../../../services/warehouseService';
import { SellerMasterView } from '../../sellers/SellerMasterView';
import { sellerService } from '../../../services/sellerService';
import { RegionMasterView } from '../../regions/RegionMasterView';
import { regionService } from '../../../services/regionService';
import { CategoryMasterListView } from './CategoryMasterListView';
import { ClassificationMethodSelectorModal } from './ClassificationMethodSelectorModal';
import { categoryService, detectClassificationMode } from '../../../services/categoryService';

interface MasterDataViewProps {
  initialSubTab?: MasterDataSubTab;
  onClose: (hasUnsavedChanges?: boolean) => void;
  onNavigateSubTab?: (subTab: MasterDataSubTab) => void;
}

interface FastProductItem {
  id: string;
  code: string;
  name: string;
  unit: string;
  basicUnit?: string;
  subUnit?: string;
  conversionFactor?: number;
  type: 'stockable' | 'service';
  barcode: string;
  sellingPrice: number;
  costPrice: number;
  category: string;
  subCategory?: string;
  subSubCategory?: string;
  stockQty: number;
}

interface WarehouseRecord {
  id: string;
  internalId: string; // Immutable internal system ID
  code: string;
  name: string;
  branch: string;
  hasTransactions: boolean;
  transactionCount: number;
  manager: string;
}

interface SubSubCategoryTreeNode {
  id: string;
  name: string;
  level: 3;
  itemCount: number;
}

interface SubCategoryTreeNode {
  id: string;
  name: string;
  level: 2;
  itemCount: number;
  children?: SubSubCategoryTreeNode[];
}

interface CategoryTreeNode {
  id: string;
  name: string;
  level: 1;
  children?: SubCategoryTreeNode[];
  itemCount: number;
}

export const MasterDataView: React.FC<MasterDataViewProps> = ({
  initialSubTab = 'item_tree',
  onClose,
  onNavigateSubTab
}) => {
  const [activeSubTab, setActiveSubTab] = useState<MasterDataSubTab>(initialSubTab);
  const [isDirty, setIsDirty] = useState<boolean>(false);
  const [searchQuery, setSearchQuery] = useState('');
  const [statusNotice, setStatusNotice] = useState<string | null>(null);

  // 1. FAST PRODUCTS & CATEGORY TREE STATE
  const [products, setProducts] = useState<FastProductItem[]>(() => categoryService.getProducts());
  const [categoryTree, setCategoryTree] = useState<CategoryTreeNode[]>(() => categoryService.getCategoryTree());

  // Strict Mode Detection on initial load
  const [categoryLevels, setCategoryLevels] = useState<2 | 3>(() => {
    const initialCats = categoryService.getCategoryTree();
    const initialProds = categoryService.getProducts();
    const mode = detectClassificationMode(initialCats, initialProds);
    if (mode === '3-level') return 3;
    if (mode === '2-level') return 2;
    try {
      const saved = localStorage.getItem('vertex_category_structure_levels') || localStorage.getItem('vertex_category_hierarchy_levels');
      return saved === '3' ? 3 : 2;
    } catch {
      return 2;
    }
  });

  const [isClassificationModalOpen, setIsClassificationModalOpen] = useState<boolean>(() => {
    if (initialSubTab === 'item_tree') {
      const initialCats = categoryService.getCategoryTree();
      const initialProds = categoryService.getProducts();
      const mode = detectClassificationMode(initialCats, initialProds);
      return mode === 'ask-user';
    }
    return false;
  });

  // Fast row entry inputs
  const [newProdName, setNewProdName] = useState('');
  const [newProdUnit, setNewProdUnit] = useState('عدد');
  const [newProdType, setNewProdType] = useState<'stockable' | 'service'>('stockable');
  const [newProdBarcode, setNewProdBarcode] = useState('');
  const [newProdPrice, setNewProdPrice] = useState<number>(0);
  const nextCodeNumber = products.length + 1;
  const autoGeneratedCode = `PRD-${String(nextCodeNumber).padStart(3, '0')}`;

  const productNameInputRef = useRef<HTMLInputElement>(null);

  // 2. CATEGORY TREE STATE & SYSTEM-LEVEL STRUCTURE CONFIG (2 or 3 levels)
  const [isStructureConfigured, setIsStructureConfigured] = useState<boolean>(() => {
    try {
      return localStorage.getItem('vertex_category_structure_configured') === 'true';
    } catch {
      return false;
    }
  });

  const [tempSelectedLevels, setTempSelectedLevels] = useState<2 | 3>(categoryLevels);
  const [showReconfigureWarningModal, setShowReconfigureWarningModal] = useState<boolean>(false);

  const handleAdoptCategoryStructure = () => {
    setCategoryLevels(tempSelectedLevels);
    setIsStructureConfigured(true);
    try {
      localStorage.setItem('vertex_category_structure_configured', 'true');
      localStorage.setItem('vertex_category_structure_levels', String(tempSelectedLevels));
      localStorage.setItem('vertex_category_hierarchy_levels', String(tempSelectedLevels));
    } catch (e) {
      console.error('Failed to save category structure configuration:', e);
    }
    setIsDirty(true);
    showNotice(
      tempSelectedLevels === 2
        ? 'تم اعتماد طريقة التصنيف بنجاح: مستويين (مجموعة ← صنف)'
        : 'تم اعتماد طريقة التصنيف بنجاح: 3 مستويات (مجموعة رئيسية ← مجموعة فرعية ← صنف)'
    );
  };

  const [newMainCatName, setNewMainCatName] = useState('');
  const [selectedParentCatId, setSelectedParentCatId] = useState<string>('CAT-01');
  const [newSubCatName, setNewSubCatName] = useState('');
  const [selectedSubParentCatId, setSelectedSubParentCatId] = useState<string>('SUB-01');
  const [newSubSubCatName, setNewSubSubCatName] = useState('');

  // 4. REACTIVE COUNTS (Strict Dynamic Sync with Master Services)
  const [warehouseCount, setWarehouseCount] = useState<number>(() => warehouseService.getAllWarehouses().length);
  const [treasuryCount, setTreasuryCount] = useState<number>(() => treasuryService.getAllTreasuries().length);
  const [customerCount, setCustomerCount] = useState<number>(() => customerService.getAllCustomers().length);
  const [vendorCount, setVendorCount] = useState<number>(() => vendorService.getAllVendors().length);
  const [sellerCount, setSellerCount] = useState<number>(() => sellerService.getAllSellers().length);
  const [regionCount, setRegionCount] = useState<number>(() => regionService.getAllRegions().length);

  useEffect(() => {
    const unsubWh = warehouseService.subscribe(() => {
      setWarehouseCount(warehouseService.getAllWarehouses().length);
    });
    const unsubTr = treasuryService.subscribe(() => {
      setTreasuryCount(treasuryService.getAllTreasuries().length);
    });
    const unsubCust = customerService.subscribe(() => {
      setCustomerCount(customerService.getAllCustomers().length);
    });
    const unsubVend = vendorService.subscribe(() => {
      setVendorCount(vendorService.getAllVendors().length);
    });
    const unsubSell = sellerService.subscribe(() => {
      setSellerCount(sellerService.getAllSellers().length);
    });
    const unsubReg = regionService.subscribe(() => {
      setRegionCount(regionService.getAllRegions().length);
    });
    const unsubCat = categoryService.subscribe(() => {
      const updatedTree = categoryService.getCategoryTree();
      const updatedProds = categoryService.getProducts();
      setCategoryTree(updatedTree);
      setProducts(updatedProds);

      // Auto-detect mode when data changes dynamically
      const mode = detectClassificationMode(updatedTree, updatedProds);
      if (mode === '3-level') {
        setCategoryLevels(3);
      } else if (mode === '2-level') {
        setCategoryLevels(2);
      }
    });
    return () => {
      unsubWh();
      unsubTr();
      unsubCust();
      unsubVend();
      unsubSell();
      unsubReg();
      unsubCat();
    };
  }, []);

  const subTabs = [
    { id: 'item_tree' as MasterDataSubTab, title: 'شجرة الأصناف', icon: FolderTree, count: categoryTree.length },
    { id: 'customers' as MasterDataSubTab, title: 'العملاء', icon: Users, count: customerCount },
    { id: 'suppliers' as MasterDataSubTab, title: 'الموردين', icon: Building2, count: vendorCount },
    { id: 'warehouses' as MasterDataSubTab, title: 'المخازن', icon: Store, count: warehouseCount },
    { id: 'treasuries' as MasterDataSubTab, title: 'الخزن', icon: Vault, count: treasuryCount },
    { id: 'sales_reps' as MasterDataSubTab, title: 'البائعون', icon: UserCheck, count: sellerCount },
    { id: 'regions' as MasterDataSubTab, title: 'الموقع', icon: MapPin, count: regionCount }
  ];

  const handleTabChange = (tabId: MasterDataSubTab) => {
    if (tabId === 'item_tree') {
      const mode = detectClassificationMode(categoryTree, products);
      if (mode === '3-level') {
        setCategoryLevels(3);
        setActiveSubTab('item_tree');
        setIsClassificationModalOpen(false);
      } else if (mode === '2-level') {
        setCategoryLevels(2);
        setActiveSubTab('item_tree');
        setIsClassificationModalOpen(false);
      } else {
        // Mode is 'ask-user': (0 sub-groups and 0 products)
        setIsClassificationModalOpen(true);
      }
    } else {
      setActiveSubTab(tabId);
      if (onNavigateSubTab) onNavigateSubTab(tabId);
    }
  };

  const showNotice = (msg: string) => {
    setStatusNotice(msg);
    setTimeout(() => setStatusNotice(null), 3000);
  };

  // FAST ITEM CREATION LOGIC (Enter key advances to next line directly)
  const handleFastAddProduct = (e?: React.KeyboardEvent | React.FormEvent) => {
    if (e && 'key' in e && e.key !== 'Enter') return;
    if (!newProdName.trim()) return;

    const isService = newProdType === 'service';
    const newProduct: FastProductItem = {
      id: autoGeneratedCode,
      code: autoGeneratedCode,
      name: newProdName.trim(),
      unit: newProdUnit || 'عدد',
      type: newProdType,
      barcode: newProdBarcode.trim() || `628${Math.floor(100000000 + Math.random() * 900000000)}`,
      sellingPrice: newProdPrice || 0,
      costPrice: isService ? 0 : 0, // Service default cost is 0
      category: isService ? 'خدمات ودعم فني' : 'عام',
      stockQty: isService ? 0 : 0
    };

    categoryService.saveProduct(newProduct);
    setIsDirty(true);
    showNotice(`تمت إضافة الصنف "${newProduct.name}" بنجاح (${newProduct.code})`);

    // Reset fields and keep focus in Item Name input for rapid entry
    setNewProdName('');
    setNewProdBarcode('');
    setNewProdPrice(0);
    setNewProdType('stockable');
    setNewProdUnit('عدد');

    setTimeout(() => {
      productNameInputRef.current?.focus();
    }, 50);
  };

  return (
    <div id="master-data-screen-container" className="h-full flex flex-col bg-slate-900 border border-slate-700/80 rounded-2xl shadow-xl overflow-hidden select-none font-['Cairo',sans-serif]" dir="rtl">
      {/* 1. WINDOW TITLE BAR (Unified VERTEX Master Template) */}
      <div className="relative px-5 py-3.5 bg-slate-950 border-b border-slate-800 flex items-center justify-between shrink-0 font-['Cairo',sans-serif]">
        {/* Right Icon */}
        <div className="flex items-center space-x-3 space-x-reverse">
          <div className="p-2 rounded-xl bg-amber-500/15 text-amber-400 border border-amber-500/30">
            <Layers className="w-5 h-5" />
          </div>
        </div>

        {/* Center: Title Centered, Bigger, Bold, Cairo Font */}
        <div className="absolute left-1/2 -translate-x-1/2 flex items-center justify-center pointer-events-none">
          <h2 className="text-lg sm:text-xl font-black text-slate-100 tracking-wide font-['Cairo',sans-serif]">
            شجرة الأصناف والبيانات الأساسية
          </h2>
        </div>

        {/* Left: Action Controls */}
        <div className="flex items-center space-x-2 space-x-reverse">
          {statusNotice && (
            <span className="text-xs text-emerald-400 bg-emerald-500/10 border border-emerald-500/20 px-3 py-1 rounded-full font-bold animate-fadeIn">
              ✓ {statusNotice}
            </span>
          )}
          <button
            type="button"
            onClick={() => onClose(isDirty)}
            className="h-8 px-3.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-white font-bold text-xs border border-slate-700 transition-all flex items-center space-x-1.5 space-x-reverse cursor-pointer"
          >
            <X className="w-4 h-4" />
            <span>إغلاق</span>
          </button>
        </div>
      </div>

      {/* Sub Tabs Horizontal Bar */}
      <div className="px-6 py-2.5 bg-slate-950/60 border-b border-slate-800 overflow-x-auto custom-scrollbar shrink-0 flex items-center space-x-2 space-x-reverse">
        {subTabs.map((tab) => {
          const isActive = activeSubTab === tab.id;
          const Icon = tab.icon;
          return (
            <button
              key={tab.id}
              onClick={() => handleTabChange(tab.id)}
              className={`flex items-center space-x-2 space-x-reverse px-3.5 py-2 rounded-xl text-xs font-bold transition-all shrink-0 cursor-pointer ${
                isActive 
                  ? 'bg-blue-600 text-white shadow-md shadow-blue-600/20' 
                  : 'text-slate-400 hover:text-slate-200 hover:bg-slate-800/60'
              }`}
            >
              <Icon className="w-4 h-4 shrink-0" />
              <span>{tab.title}</span>
              <span className={`text-[10px] font-mono px-1.5 py-0.2 rounded-full ${
                isActive ? 'bg-white/20 text-white' : 'bg-slate-800 text-slate-400'
              }`}>
                {tab.count}
              </span>
            </button>
          );
        })}
      </div>

      {/* Main Workspace Body */}
      <div className="flex-1 p-6 overflow-y-auto custom-scrollbar bg-slate-900">
        {/* ========================================================= */}
        {/* 1. PRODUCTS & FAST ITEM ENTRY */}
        {/* ========================================================= */}
        {activeSubTab === 'products' && (
          <div className="space-y-6 animate-fadeIn">
            {/* Fast Entry Box */}
            <div className="p-4 bg-slate-950 rounded-2xl border border-slate-800 shadow-lg space-y-3">
              <div className="flex items-center justify-between pb-2 border-b border-slate-800">
                <div className="flex items-center space-x-2 space-x-reverse">
                  <Package className="w-4 h-4 text-amber-400" />
                  <span className="text-xs font-bold text-slate-200">إدخال سريع للأصناف</span>
                </div>
              </div>

              {/* Fast Row Form */}
              <div className="grid grid-cols-1 sm:grid-cols-12 gap-3 items-end">
                {/* Auto Code */}
                <div className="sm:col-span-2">
                  <label className="block text-[11px] font-bold text-slate-400 mb-1">الكود التلقائي</label>
                  <input
                    type="text"
                    value={autoGeneratedCode}
                    disabled
                    className="w-full bg-slate-900 border border-slate-800 rounded-xl px-3 py-2 text-xs font-mono font-bold text-amber-400 cursor-not-allowed text-center"
                  />
                </div>

                {/* Product Name (Main Input with Enter Trigger) */}
                <div className="sm:col-span-4">
                  <label className="block text-[11px] font-bold text-slate-300 mb-1">
                    اسم الصنف <span className="text-rose-400">*</span>
                  </label>
                  <input
                    ref={productNameInputRef}
                    type="text"
                    value={newProdName}
                    onChange={(e) => setNewProdName(e.target.value)}
                    onKeyDown={handleFastAddProduct}
                    placeholder="اكتب اسم الصنف ثم اضغط Enter..."
                    className="w-full bg-slate-900 border border-slate-700 focus:border-blue-500 rounded-xl px-3.5 py-2 text-xs text-slate-100 focus:outline-none"
                    autoFocus
                  />
                </div>

                {/* Unit Dropdown (Default: عدد) */}
                <div className="sm:col-span-2">
                  <label className="block text-[11px] font-bold text-slate-400 mb-1">الوحدة (الافتراضي: عدد)</label>
                  <select
                    value={newProdUnit}
                    onChange={(e) => setNewProdUnit(e.target.value)}
                    className="w-full bg-slate-900 border border-slate-700 rounded-xl px-2.5 py-2 text-xs text-slate-200 focus:outline-none focus:border-blue-500"
                  >
                    <option value="عدد">عدد (قطعة)</option>
                    <option value="كرتونة">كرتونة</option>
                    <option value="طرد">طرد</option>
                    <option value="كيلوجرام">كيلوجرام</option>
                    <option value="ساعة خدمة">ساعة خدمة</option>
                  </select>
                </div>

                {/* Item Type (Default: مخزني vs خدمي) */}
                <div className="sm:col-span-2">
                  <label className="block text-[11px] font-bold text-slate-400 mb-1">نوع الصنف</label>
                  <select
                    value={newProdType}
                    onChange={(e) => setNewProdType(e.target.value as 'stockable' | 'service')}
                    className={`w-full border rounded-xl px-2.5 py-2 text-xs font-bold focus:outline-none ${
                      newProdType === 'service' 
                        ? 'bg-purple-950/40 border-purple-500/50 text-purple-300' 
                        : 'bg-slate-900 border-slate-700 text-slate-200'
                    }`}
                  >
                    <option value="stockable">مخزني (سلعي)</option>
                    <option value="service">خدمي (Service)</option>
                  </select>
                </div>

                {/* Barcode (Optional Unique) */}
                <div className="sm:col-span-2 flex gap-2">
                  <div className="flex-1">
                    <label className="block text-[11px] font-bold text-slate-400 mb-1">الباركود (اختياري)</label>
                    <input
                      type="text"
                      value={newProdBarcode}
                      onChange={(e) => setNewProdBarcode(e.target.value)}
                      onKeyDown={handleFastAddProduct}
                      placeholder="International Barcode"
                      className="w-full bg-slate-900 border border-slate-700 rounded-xl px-2.5 py-2 text-xs font-mono text-slate-200 focus:outline-none text-left"
                      dir="ltr"
                    />
                  </div>
                  <button
                    type="button"
                    onClick={() => handleFastAddProduct()}
                    className="self-end px-3 py-2 bg-blue-600 hover:bg-blue-500 text-white font-bold rounded-xl text-xs cursor-pointer shadow-md shadow-blue-600/20"
                    title="إضافة الصنف"
                  >
                    <Plus className="w-4 h-4" />
                  </button>
                </div>
              </div>

              {/* Service Item Explanatory Helper */}
              {newProdType === 'service' && (
                <div className="p-2 bg-purple-950/40 border border-purple-500/30 rounded-xl flex items-center space-x-2 space-x-reverse text-purple-300 text-xs animate-fadeIn">
                  <Info className="w-4 h-4 shrink-0" />
                  <span>
                    <strong>الصنف الخدمي:</strong> لا يدخل في جرد المخزون السلعي.
                  </span>
                </div>
              )}
            </div>

            {/* Products Table */}
            <div className="rounded-2xl border border-slate-800 bg-slate-950/60 overflow-hidden shadow-sm">
              <div className="p-3.5 bg-slate-900/80 border-b border-slate-800 flex items-center justify-between">
                <span className="text-xs font-bold text-slate-200">سجل الأصناف المسجلة ({products.length} صنف)</span>
                <div className="w-64 relative">
                  <Search className="w-3.5 h-3.5 absolute right-3 top-2.5 text-slate-500" />
                  <input
                    type="text"
                    value={searchQuery}
                    onChange={(e) => setSearchQuery(e.target.value)}
                    placeholder="بحث في الأصناف..."
                    className="w-full bg-slate-950 border border-slate-800 rounded-lg pr-9 pl-3 py-1.5 text-xs text-slate-200 focus:outline-none"
                  />
                </div>
              </div>

              <div className="overflow-x-auto">
                <table className="w-full text-right text-xs">
                  <thead className="bg-slate-900 border-b border-slate-800 text-slate-400 font-bold">
                    <tr>
                      <th className="p-3">كود الصنف</th>
                      <th className="p-3">اسم الصنف</th>
                      <th className="p-3">النوع</th>
                      <th className="p-3">الوحدة</th>
                      <th className="p-3">الباركود</th>
                      <th className="p-3 text-left">سعر البيع</th>
                      <th className="p-3 text-left">التكلفة</th>
                      <th className="p-3 text-center">المخزون الحالي</th>
                      <th className="p-3 text-center">إجراءات</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-800/60 font-medium">
                    {products
                      .filter(p => p.name.includes(searchQuery) || p.code.includes(searchQuery) || p.barcode.includes(searchQuery))
                      .map((prod) => (
                        <tr key={prod.id} className="hover:bg-slate-850/60 transition-colors">
                          <td className="p-3 font-mono font-bold text-amber-400">{prod.code}</td>
                          <td className="p-3 text-slate-100 font-bold">{prod.name}</td>
                          <td className="p-3">
                            <span className={`px-2 py-0.5 rounded-full text-[10px] font-bold ${
                              prod.type === 'service'
                                ? 'bg-purple-500/10 text-purple-400 border border-purple-500/20'
                                : 'bg-emerald-500/10 text-emerald-400 border border-emerald-500/20'
                            }`}>
                              {prod.type === 'service' ? 'خدمي' : 'مخزني'}
                            </span>
                          </td>
                          <td className="p-3 text-slate-300">{prod.unit}</td>
                          <td className="p-3 font-mono text-slate-400" dir="ltr">{prod.barcode}</td>
                          <td className="p-3 text-left font-mono font-bold text-slate-100">${prod.sellingPrice.toFixed(2)}</td>
                          <td className="p-3 text-left font-mono text-slate-400">
                            {prod.type === 'service' ? '$0.00 (خدمة)' : `$${prod.costPrice.toFixed(2)}`}
                          </td>
                          <td className="p-3 text-center font-mono">
                            {prod.type === 'service' ? (
                              <span className="text-slate-500 text-[11px]">— لا ينطبق —</span>
                            ) : (
                              <span className="text-emerald-400 font-bold">{prod.stockQty}</span>
                            )}
                          </td>
                          <td className="p-3 text-center">
                            <button
                              type="button"
                              onClick={() => {
                                categoryService.deleteProduct(prod.id);
                                setIsDirty(true);
                              }}
                              className="text-slate-500 hover:text-rose-400 p-1 rounded-lg hover:bg-slate-800 transition-colors cursor-pointer"
                              title="حذف الصنف"
                            >
                              <Trash2 className="w-3.5 h-3.5" />
                            </button>
                          </td>
                        </tr>
                      ))}
                  </tbody>
                </table>
              </div>
            </div>
          </div>
        )}

        {/* ========================================================= */}
        {/* 2. CATEGORY & PRODUCTS MASTER DATA LIST (CategoryMasterListView) */}
        {/* ========================================================= */}
        {activeSubTab === 'item_tree' && (
          <CategoryMasterListView
            products={products}
            setProducts={setProducts}
            categoryTree={categoryTree}
            setCategoryTree={setCategoryTree}
            categoryLevels={categoryLevels}
            setCategoryLevels={setCategoryLevels}
            isStructureConfigured={isStructureConfigured}
            setIsStructureConfigured={setIsStructureConfigured}
            onDirtyChange={(dirty) => setIsDirty(dirty)}
            showNotice={showNotice}
          />
        )}

        {/* ========================================================= */}
        {/* 3. WAREHOUSES SUB-TAB (Dedicated Warehouse Master Screen) */}
        {/* ========================================================= */}
        {activeSubTab === 'warehouses' && (
          <div className="h-full animate-fadeIn">
            <WarehouseMasterView
              onClose={() => setActiveSubTab('item_tree')}
              onNavigateSection={onNavigateSubTab ? () => onNavigateSubTab('item_tree') : undefined}
            />
          </div>
        )}

        {/* ========================================================= */}
        {/* 4. CUSTOMERS SUB-TAB (Unified Customer Master from Sales) */}
        {/* ========================================================= */}
        {activeSubTab === 'customers' && (
          <div className="h-full animate-fadeIn">
            <CustomerMasterView
              onClose={() => setActiveSubTab('item_tree')}
              onNavigateSection={onNavigateSubTab ? () => onNavigateSubTab('item_tree') : undefined}
            />
          </div>
        )}

        {/* ========================================================= */}
        {/* 5. SUPPLIERS SUB-TAB (Unified Vendor Master from Purchases) */}
        {/* ========================================================= */}
        {activeSubTab === 'suppliers' && (
          <div className="h-full animate-fadeIn">
            <VendorMasterView
              onClose={() => setActiveSubTab('item_tree')}
              onNavigateSection={onNavigateSubTab ? () => onNavigateSubTab('item_tree') : undefined}
            />
          </div>
        )}

        {/* ========================================================= */}
        {/* 6. TREASURIES SUB-TAB (Dedicated Treasury Master Screen) */}
        {/* ========================================================= */}
        {activeSubTab === 'treasuries' && (
          <div className="h-full animate-fadeIn">
            <TreasuryMasterView
              onClose={() => setActiveSubTab('item_tree')}
              onNavigateSection={onNavigateSubTab ? () => onNavigateSubTab('item_tree') : undefined}
            />
          </div>
        )}

        {/* ========================================================= */}
        {/* 7. SELLERS SUB-TAB (Dedicated Seller Master Screen) */}
        {/* ========================================================= */}
        {activeSubTab === 'sales_reps' && (
          <div className="h-full animate-fadeIn">
            <SellerMasterView
              onClose={() => setActiveSubTab('item_tree')}
              onNavigateSection={onNavigateSubTab ? () => onNavigateSubTab('item_tree') : undefined}
            />
          </div>
        )}

        {/* ========================================================= */}
        {/* 8. REGIONS SUB-TAB (Dedicated Region Master Screen) */}
        {/* ========================================================= */}
        {activeSubTab === 'regions' && (
          <div className="h-full animate-fadeIn">
            <RegionMasterView
              onClose={() => setActiveSubTab('item_tree')}
              onNavigateSection={onNavigateSubTab ? () => onNavigateSubTab('item_tree') : undefined}
            />
          </div>
        )}
      </div>

      {/* Classification Method Selection Modal */}
      {isClassificationModalOpen && (
        <ClassificationMethodSelectorModal
          isOpen={isClassificationModalOpen}
          initialMode={categoryLevels === 3 ? '3-level' : '2-level'}
          onClose={() => setIsClassificationModalOpen(false)}
          onConfirm={(selectedMode) => {
            const levels = selectedMode === '3-level' ? 3 : 2;
            setCategoryLevels(levels);
            setTempSelectedLevels(levels);
            try {
              localStorage.setItem('vertex_category_structure_levels', String(levels));
              localStorage.setItem('vertex_category_hierarchy_levels', String(levels));
            } catch (e) {
              console.error(e);
            }
            setActiveSubTab('item_tree');
            setIsClassificationModalOpen(false);
          }}
        />
      )}
    </div>
  );
};
