// Simple SHA-256 style hash generator for tamper protection demonstration
const calculateHash = (evtId: string, timestamp: string, user: string, summary: string): string => {
  let hash = 0;
  const str = `${evtId}:${timestamp}:${user}:${summary}:VERTEX_SECRET_KEY`;
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = (hash << 5) - hash + char;
    hash |= 0;
  }
  return '0x' + Math.abs(hash).toString(16).padStart(8, '0') + 'f7b3a9e1';
};

