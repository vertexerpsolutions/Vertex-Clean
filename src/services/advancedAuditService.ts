class AdvancedAuditService {
  private state: AuditState;

  constructor() {
    this.state = this.loadInitialState();
  }

  private loadInitialState(): AuditState {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved) {
        const parsed = JSON.parse(saved);
        return {
          ...parsed,
          events: parsed.events || INITIAL_AUDIT_EVENTS
        };
      }
    } catch (e) {
      console.warn('Failed to parse Advanced Audit state:', e);
    }

    return {
      events: INITIAL_AUDIT_EVENTS,
      isVgf10Completed: true
    };
  }

  public getState(): AuditState {
    return this.state;
  }

  public saveState(): void {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(this.state));
    } catch (e) {
      console.warn('Failed to save Advanced Audit state:', e);
    }
  }

  public logEvent(
    category: AuditCategory,
    action: ActivityAction,
    user: string,
    userRole: string,
    department: string,
    summary: string,
    entityType?: EntityType,
    entityId?: string,
    entityName?: string,
    changes?: EntityChange[],
    reason?: string,
    severity: 'low' | 'medium' | 'high' | 'critical' = 'low'
  ): AuditEvent {
    const id = `AUD-${Date.now().toString().slice(-4)}`;
    const timestamp = new Date().toISOString();
    const hashSignature = calculateHash(id, timestamp, user, summary);

    const newEvt: AuditEvent = {
      id,
      timestamp,
      category,
      action,
      user,
      userRole,
      department,
      ipAddress: '192.168.1.100',
      deviceInfo: 'Chrome 127 / Vertex Desktop Agent',
      sessionId: `SES-${Math.floor(100000 + Math.random() * 900000)}-V`,
      entityType,
      entityId,
      entityName,
      summary,
      reason,
      changes,
      hashSignature,
      isVerified: true,
      severity
    };

    this.state.events.unshift(newEvt);
    this.saveState();
    return newEvt;
  }

  public verifyTamperProtection(): { total: number; verified: number; corrupted: number } {
    let verified = 0;
    let corrupted = 0;

    this.state.events.forEach(evt => {
      const expectedHash = calculateHash(evt.id, evt.timestamp, evt.user, evt.summary);
      if (evt.hashSignature === expectedHash) {
        evt.isVerified = true;
        verified++;
      } else {
        evt.isVerified = false;
        corrupted++;
      }
    });

    this.saveState();
    return { total: this.state.events.length, verified, corrupted };
  }

  public getStats(): AuditTimelineStats {
    const { events } = this.state;
    const totalEvents = events.length;
    const securityEventsCount = events.filter(e => e.category === 'Security').length;
    const businessEventsCount = events.filter(e => e.category === 'Business').length;
    const entityChangesCount = events.filter(e => e.category === 'Entity Change' || e.changes?.length).length;
    const userLoginsCount = events.filter(e => e.action === 'Login').length;
    const verifiedCount = events.filter(e => e.isVerified).length;
    const tamperIntegrityPct = totalEvents > 0 ? (verifiedCount / totalEvents) * 100 : 100;

    return {
      totalEvents,
      securityEventsCount,
      businessEventsCount,
      entityChangesCount,
      userLoginsCount,
      tamperIntegrityPct
    };
  }

  public markVgf10Completed(): void {
    this.state.isVgf10Completed = true;
    this.saveState();
  }

  public resetState(): void {
    localStorage.removeItem(STORAGE_KEY);
    this.state = this.loadInitialState();
  }
}

export const advancedAuditService = new AdvancedAuditService();
