export type AuditCategory = 'System' | 'Security' | 'Business' | 'User Activity' | 'Entity Change';

export type ActivityAction = 
  | 'Login' 
  | 'Logout' 
  | 'Create' 
  | 'Update' 
  | 'Delete' 
  | 'Approve' 
  | 'Reject' 
  | 'Print' 
  | 'Export' 
  | 'Import';

export type EntityType = 
  | 'Customers' 
  | 'Suppliers' 
  | 'Items' 
  | 'Accounts' 
  | 'Invoices' 
  | 'Payments' 
  | 'Inventory' 
  | 'Assets' 
  | 'Users' 
  | 'System Settings';

export interface EntityChange {
  field: string;
  oldValue: any;
  newValue: any;
}

export interface AuditEvent {
  id: string;
  timestamp: string;
  category: AuditCategory;
  action: ActivityAction;
  user: string;
  userRole: string;
  department: string;
  ipAddress: string;
  deviceInfo: string;
  sessionId: string;
  entityType?: EntityType;
  entityId?: string;
  entityName?: string;
  summary: string;
  reason?: string;
  changes?: EntityChange[];
  hashSignature: string; // Tamper protection hash
  isVerified: boolean;
  severity: 'low' | 'medium' | 'high' | 'critical';
}

export interface AuditTimelineStats {
  totalEvents: number;
  securityEventsCount: number;
  businessEventsCount: number;
  entityChangesCount: number;
  userLoginsCount: number;
  tamperIntegrityPct: number;
}

export interface AuditState {
  events: AuditEvent[];
  isVgf10Completed: boolean;
}

